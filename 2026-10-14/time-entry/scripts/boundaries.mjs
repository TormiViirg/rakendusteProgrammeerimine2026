// Regenerates tests/BOUNDARIES.md from the test sources:  node scripts/boundaries.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const walk = (dir) => readdirSync(dir).flatMap((n) => (statSync(join(dir, n)).isDirectory() ? walk(join(dir, n)) : [join(dir, n)]));
const files = walk('tests').filter((f) => /\.(test|spec)\.ts$/.test(f)).sort();
const ID = '(?:EC|BV|INV|UI|I18N)-[A-Z0-9]+(?:-[A-Z0-9]+)*';
const rows = [];
for (const file of files) {
  const source = readFileSync(file, 'utf8');
  const seen = new Set();
  const add = (id, text) => {
    const key = `${id}|${text}`;
    if (seen.has(key)) return;
    seen.add(key);
    rows.push({ file: relative('tests', file), id, text: text.replace(/\$\{[^}]+\}/g, '…').replace(/\|/g, '/').replace(/\\'/g, "'").trim() });
  };
  // table rows: { id: 'BV-…', boundary|klass|situation: '…' }
  for (const m of source.matchAll(new RegExp(`id: '(${ID})[^']*',\\s*(?:boundary|klass|situation): '((?:[^'\\\\]|\\\\.)*)'`, 'g'))) add(m[1], m[2]);
  // table rows whose id carries the description: { id: 'EC-… text', … }
  for (const m of source.matchAll(new RegExp(`id: '(${ID}) ([^']+)'`, 'g'))) add(m[1], m[2]);
  // plain titles: it('BV-… text', …) / test(`UI-… [lang] text`, …)
  for (const m of source.matchAll(new RegExp(`(?:it|test)\\((['"\`])(${ID}) ((?:(?!\\1).)*)\\1`, 'g'))) add(m[2], m[3]);
}
const kind = { EC: 'equivalence class', BV: 'boundary value', INV: 'invariant (randomised)', UI: 'UI behaviour', I18N: 'translation completeness' };
let out = `# Boundary and equivalence catalogue

Generated by \`node scripts/boundaries.mjs\` – do not edit by hand.

Every test carries an id. The prefix says what kind of case it is:

| Prefix | Meaning |
| --- | --- |
| \`EC-\` | **Equivalence class** – one representative of a group of inputs that must behave alike |
| \`BV-\` | **Boundary value** – the exact edge between two classes, or the value right next to it |
| \`INV-\` | **Invariant** – a property that must survive hundreds of generated edits |
| \`UI-\` | **UI behaviour** in a real browser (Playwright); language and width are in the title |
| \`I18N-\` | Every engine message exists in ET / EN / RU with the plural forms that language needs |

Named situations used across the suite:

| Name | What it is | Where |
| --- | --- | --- |
| **past midnight** | a window or interval that crosses 24:00 and stays under the day it started on | \`BV-RES-*\`, \`BV-SNAP-05\`, \`BV-SCALE-03/04\`, \`BV-PAST-07\`, \`BV-FACT-01\`, \`UI-PM-01\`, \`UI-NIGHT-01\` |
| **B2B-48H** | two admin windows back to back, together covering 48 hours | \`BV-B2B-*\`, \`BV-SCALE-06\`, \`EC-RES-09\`, \`UI-B2B-01\` |
| **grace point** | the instant \`window start − harshest grace\`; 1 ms before / exactly at | \`BV-GRACE-*\`, \`EC-EDIT-07…10\`, \`UI-LOCK-*\` |
| **past day** | window end reached; 1 ms before / exactly at | \`BV-PAST-*\`, \`EC-EDIT-11/12\`, \`UI-PAST-*\` |
| **range edge** | typed time one step outside / exactly on the window bound | \`BV-RES-04…07\`, \`BV-SNAP-03/04\`, \`UI-RNG-*\` |
| **half step** | 2 min 30 s – the rounding tie for the 5-minute step | \`BV-RND-03\`, \`UI-RND-01\` |
| **week ↔ range** | five day columns fit / only four fit | \`BV-PAGE-02/03\`, \`UI-COL-01\` |
| **no window** | a day the admin entered nothing for → crossed out for the whole day | \`EC-CLOSED-01\`, \`UI-NOWIN-01\` |
| **several teams** | windows that collide (two lanes) or not (shared lane); harsher grace for both | \`*-LANE-*\`, \`*-TEAM-*\` |
| **DST** | the two days a year Tallinn's clock jumps | \`BV-DST-01/02\` |
`;
let current = '';
for (const r of rows) {
  if (r.file !== current) {
    current = r.file;
    out += `\n## ${current}\n\n| Id | Kind | Partition / boundary under test |\n| --- | --- | --- |\n`;
  }
  out += `| \`${r.id}\` | ${kind[r.id.split('-')[0]]} | ${r.text} |\n`;
}
writeFileSync('tests/BOUNDARIES.md', out);
console.log(`${rows.length} cases from ${files.length} files`);
